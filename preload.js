const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listProjects: () => ipcRenderer.invoke('projects:list'),
  addProject: () => ipcRenderer.invoke('projects:add'),
  hideProject: (p) => ipcRenderer.invoke('projects:hide', p),
  revealProject: (p) => ipcRenderer.invoke('projects:reveal', p),
  pickFiles: () => ipcRenderer.invoke('dialog:files'),
  saveAttachment: (bytes, mime) => ipcRenderer.invoke('attachments:save', bytes, mime),
  pathForFile: (file) => webUtils.getPathForFile(file),
  fileExists: (p) => ipcRenderer.invoke('file:exists', p),
  openFile: (p) => ipcRenderer.invoke('file:open', p),
  showFile: (p) => ipcRenderer.invoke('file:show', p),
  sessionState: (id, agent) => ipcRenderer.invoke('sessions:state', id, agent),
  renameSession: (id, title, agent) => ipcRenderer.invoke('sessions:rename', id, title, agent),
  deleteSession: (id, title, agent) => ipcRenderer.invoke('sessions:delete', id, title, agent),
  onProjectsChanged: (cb) => ipcRenderer.on('projects:changed', () => cb()),
  onBrowserNewTab: (cb) => ipcRenderer.on('browser:new-tab', (_e, url) => cb(url)),
  onBrowserShortcut: (cb) => ipcRenderer.on('browser:shortcut', (_e, k) => cb(k)),

  gitRoot: (cwd) => ipcRenderer.invoke('git:root', cwd),
  git: (cwd, args, input) => ipcRenderer.invoke('git:run', cwd, args, input),
  listFiles: (root, rel) => ipcRenderer.invoke('files:list', root, rel),
  readFile: (root, rel) => ipcRenderer.invoke('files:read', root, rel),
  writeFile: (root, rel, text) => ipcRenderer.invoke('files:write', root, rel, text),
  searchFiles: (root, query, mode) => ipcRenderer.invoke('files:search', root, query, mode),
  gitIgnore: (root, pattern) => ipcRenderer.invoke('git:ignore', root, pattern),

  listHosts: () => ipcRenderer.invoke('hosts:list'),
  saveHost: (h) => ipcRenderer.invoke('hosts:save', h),
  deleteHost: (id) => ipcRenderer.invoke('hosts:delete', id),
  testHost: (id) => ipcRenderer.invoke('hosts:test', id),
  disconnectHost: (id) => ipcRenderer.invoke('hosts:disconnect', id),
  hostWorkspace: (id) => ipcRenderer.invoke('hosts:workspace', id),
  sshShell: (opts) => ipcRenderer.invoke('ssh:shell', opts),
  hostActivity: (id) => ipcRenderer.invoke('hosts:activity', id),
  importHosts: () => ipcRenderer.invoke('hosts:import'),
  pickKey: () => ipcRenderer.invoke('hosts:pick-key'),
  installSkill: () => ipcRenderer.invoke('hosts:install-skill'),
  canSeal: () => ipcRenderer.invoke('hosts:can-seal'),
  onHostsChanged: (cb) => ipcRenderer.on('ssh:hosts-changed', () => cb()),
  onHostActivity: (cb) => ipcRenderer.on('ssh:activity', (_e, id) => cb(id)),
  onSshPrompt: (cb) => ipcRenderer.on('ssh:prompt', (_e, p) => cb(p)),
  onSshPromptCancel: (cb) => ipcRenderer.on('ssh:prompt-cancel', (_e, id) => cb(id)),
  answerSsh: (id, answer) => ipcRenderer.send('ssh:answer', id, answer),

  listAgents: () => ipcRenderer.invoke('agents:list'),
  codexModels: () => ipcRenderer.invoke('agents:codex-models'),
  saveAgent: (a) => ipcRenderer.invoke('agents:save', a),
  deleteAgent: (id) => ipcRenderer.invoke('agents:delete', id),
  listRuns: () => ipcRenderer.invoke('agents:runs'),
  stopRun: (id) => ipcRenderer.invoke('agents:stop', id),
  onRun: (cb) => ipcRenderer.on('crew:run', (_e, r) => cb(r)),

  getUsage: (force) => ipcRenderer.invoke('usage:get', force),
  onUsageChanged: (cb) => ipcRenderer.on('usage:changed', () => cb()),

  egoStatus: () => ipcRenderer.invoke('ego:status'),

  listProviders: () => ipcRenderer.invoke('providers:list'),
  saveProvider: (p) => ipcRenderer.invoke('providers:save', p),
  deleteProvider: (id) => ipcRenderer.invoke('providers:delete', id),
  fetchProviderModels: (q) => ipcRenderer.invoke('providers:fetch-models', q),
  pickProviderIcon: () => ipcRenderer.invoke('providers:pick-icon'),
  providerBindings: () => ipcRenderer.invoke('providers:bindings'),
  bindProvider: (sessionId, providerId, picks) => ipcRenderer.invoke('providers:bind', sessionId, providerId, picks),

  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (patch) => ipcRenderer.invoke('config:set', patch),

  spawn: (opts) => ipcRenderer.invoke('pty:spawn', opts),
  checkAgent: (agent) => ipcRenderer.invoke('agent:check', agent),
  installAgent: (opts) => ipcRenderer.invoke('pty:install', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  rekey: (id, sessionId) => ipcRenderer.send('pty:rekey', id, sessionId),
  onData: (cb) => ipcRenderer.on('pty:data', (_e, id, data) => cb(id, data)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),
});
