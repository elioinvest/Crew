/// The whole dictionary, for what the table above doesn't list.
static ORIGINAL: std::sync::LazyLock<std::collections::HashMap<&'static str, &'static str>> =
    std::sync::LazyLock::new(|| {
        // Owned while parsing: a string with an escape in it can't be borrowed from the file.
        let all: std::collections::HashMap<String, String> = serde_json::from_str(include_str!("../assets/zh.json")).unwrap_or_default();
        all.into_iter().map(|(k, v)| (&*k.leak(), &*v.leak())).collect()
    });

/// The translation of text only known at run time, like menu labels passed around as strings.
pub fn lookup(text: &str) -> Option<&'static str> {
    if !zh() {
        return None;
    }
    ORIGINAL.get(text).copied()
}

