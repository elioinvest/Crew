//! Chinese for what this version shows. The interface is written in English
//! and the language setting ("auto", "en" or "zh") picks the translation.

use std::sync::atomic::{AtomicBool, Ordering};

static ZH: AtomicBool = AtomicBool::new(false);

pub fn init(setting: &str) {
    let zh = match setting {
        "zh" => true,
        "en" => false,
        _ => sys_locale::get_locale().is_some_and(|l| l.to_lowercase().starts_with("zh")),
    };
    ZH.store(zh, Ordering::Relaxed);
}

pub fn zh() -> bool {
    ZH.load(Ordering::Relaxed)
}

pub fn show_more(count: usize) -> String {
    if ZH.load(Ordering::Relaxed) { format!("再显示 {count} 个") } else { format!("Show {count} more") }
}

